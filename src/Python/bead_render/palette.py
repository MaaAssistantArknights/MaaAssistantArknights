_PALETTE_LAB = None


def get_palette_lab():
    """预计算 40 色板的 LAB 表示（(40,3) float32），用于最近邻匹配"""
    global _PALETTE_LAB
    if _PALETTE_LAB is None:
        arr = np.uint8([[c] for c in PERLER_PALETTE])
        _PALETTE_LAB = cv2.cvtColor(arr, cv2.COLOR_RGB2LAB)[:, 0, :].astype(np.float32)
    return _PALETTE_LAB
